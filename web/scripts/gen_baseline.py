"""Emit shared fixtures plus the Python scores, for the TypeScript port to match.

Run from the repository root:  python web/scripts/gen_baseline.py web/scripts/baseline.json
"""

import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, ROOT)

from sentence_transformers import SentenceTransformer  # noqa: E402

import analyzer  # noqa: E402
import eval_analyzer as ev  # noqa: E402

out_path = sys.argv[1]

model = SentenceTransformer("all-MiniLM-L6-v2")

pairs = [
    ("ml_resume", "ml_jd"),
    ("analyst_resume", "ml_jd"),
    ("frontend_resume", "ml_jd"),
    ("frontend_resume", "frontend_jd"),
    ("ml_resume", "frontend_jd"),
]

documents = {
    "ml_resume": ev.ML_RESUME,
    "analyst_resume": ev.ANALYST_RESUME,
    "frontend_resume": ev.FRONTEND_RESUME,
    "ml_jd": ev.ML_JD,
    "frontend_jd": ev.FRONTEND_JD,
}

cases = []
for resume_key, jd_key in pairs:
    result = analyzer.analyze(documents[resume_key], documents[jd_key], model)
    cases.append(
        {
            "resume": resume_key,
            "jd": jd_key,
            "overall": result.overall,
            "skillPercent": result.skill_percent,
            "requirementPercent": result.requirement_percent,
            "verdict": result.verdict,
            "requirementCount": len(result.requirements),
            "resumeChunks": result.resume_chunks,
            "missingRequired": sorted(s.name for s in result.missing_required),
            "matched": sorted(s.name for s in result.matched),
            "statuses": [r.status for r in result.requirements],
            "yearsRequired": result.years_required,
            "yearsEstimated": result.years_estimated,
        }
    )

payload = {
    "note": "Generated by web/scripts/gen_baseline.py from the Python analyzer.",
    "documents": documents,
    "cases": cases,
}

with open(out_path, "w", encoding="utf-8", newline="\n") as fh:
    json.dump(payload, fh, indent=2)
    fh.write("\n")

print(f"wrote {out_path}")
for case in cases:
    print(
        f"  {case['resume']:<17}{case['jd']:<14}"
        f"{case['overall']:>4}%  skills {case['skillPercent']:>3}%  reqs {case['requirementPercent']:>3}%"
    )
